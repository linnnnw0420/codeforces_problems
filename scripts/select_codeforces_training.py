#!/usr/bin/env python3
"""Draw a balanced 20-problem Codeforces training set using official API data.

Never includes a problem submitted before by the specified handle.
Output is a fixed, reproducible training set, not regenerated by daily sync.
"""
import argparse
from collections import Counter
from datetime import datetime, timezone
import json
from pathlib import Path
import random

from fetch_codeforces import api, atomic_json


# Each focus appears once except DP (twice). Difficulty follows measured profile:
# 3 x 1100, 4 x 1200, 6 x 1300, 4 x 1400, 3 x 1500.
TARGETS = [
    ("implementation", 1100),
    ("math", 1100),
    ("sortings", 1100),
    ("binary search", 1200),
    ("greedy", 1200),
    ("strings", 1200),
    ("geometry", 1200),
    ("two pointers", 1300),
    ("dp", 1300),
    ("constructive algorithms", 1300),
    ("number theory", 1300),
    ("bitmasks", 1300),
    ("data structures", 1300),
    ("dfs and similar", 1400),
    ("graphs", 1400),
    ("trees", 1400),
    ("combinatorics", 1400),
    ("shortest paths", 1500),
    ("dsu", 1500),
    ("dp", 1500),
]

def key(p):
    return (p.get("contestId"), str(p.get("index")))

def choose(problems, solved_count, attempted, names, seed):
    selected = []
    used_contests = set()
    secondary_count = Counter()
    focus_count = Counter()
    rng = random.Random(seed)
    for topic, rating in TARGETS:
        candidates = [
            p for p in problems
            if p.get("type") == "PROGRAMMING"
            and p.get("rating") == rating
            and topic in p.get("tags", [])
            and p.get("contestId", 0) >= 1100
            and p.get("contestId") not in used_contests
            and key(p) not in attempted
            and p.get("name") not in names
            and not ({"interactive", "*special"} & set(p.get("tags", [])))
            and solved_count.get(key(p), 0) >= 3000
        ]
        if not candidates:
            raise RuntimeError(f"No fresh problem candidates: {topic} rating {rating}")
        # Minimize repeated secondary concepts while keeping a seeded, genuinely random
        # choice among similarly diverse items. Focus topics are fixed by TARGETS.
        scored = []
        for p in candidates:
            tags = p.get("tags", [])
            extra = [t for t in tags if t != topic]
            overlap = sum(secondary_count[t] for t in extra)
            # Small random jitter prevents repeatedly picking the first problem alphabetically.
            cost = overlap * 4 + len(extra) * 0.8 + rng.uniform(0, 6)
            scored.append((cost, p))
        scored.sort(key=lambda pair: pair[0])
        best = scored[0][1]
        used_contests.add(best["contestId"])
        focus_count[topic] += 1
        for t in best.get("tags", []):
            secondary_count[t] += 1
        selected.append({
            "number": len(selected) + 1,
            "contestId": best["contestId"],
            "index": best["index"],
            "name": best["name"],
            "rating": best["rating"],
            "focus": topic,
            "tags": best.get("tags", []),
            "solvedCount": solved_count.get(key(best), 0),
            "url": f"https://codeforces.com/problemset/problem/{best['contestId']}/{best['index']}",
            "status": "unattempted_as_of_snapshot",
        })
    return selected

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--submissions", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--handle", default="Linw04207")
    parser.add_argument("--seed", type=int, default=20261103)
    args = parser.parse_args()

    submissions = json.loads(args.submissions.read_text(encoding="utf-8"))["result"]
    attempted = {key(s["problem"]) for s in submissions}
    names = {s["problem"].get("name") for s in submissions}
    print(f"Filtering against {len(submissions)} submissions and {len(attempted)} attempted problems", flush=True)

    dataset = api("problemset.problems")
    problems = dataset["problems"]
    solved_count = {key(s): s["solvedCount"] for s in dataset.get("problemStatistics", [])}
    print(f"Official catalog: {len(problems)} problems", flush=True)

    selected = choose(problems, solved_count, attempted, names, args.seed)
    if len(selected) != 20 or len({(x["contestId"], x["index"]) for x in selected}) != 20:
        raise RuntimeError("Selection incomplete or contains duplicate problems")
    result = {
        "handle": args.handle,
        "source": "Codeforces official API problemset.problems + user.status",
        "generated_at_utc": datetime.now(timezone.utc).isoformat(),
        "seed": args.seed,
        "submission_count_filtered": len(submissions),
        "unique_attempted_filtered": len(attempted),
        "problem_catalog_size": len(problems),
        "focus_counts": dict(Counter(x["focus"] for x in selected)),
        "rating_counts": dict(sorted(Counter(x["rating"] for x in selected).items())),
        "problems": selected,
    }
    args.out.mkdir(parents=True, exist_ok=True)
    atomic_json(args.out / "training_20.json", result)
    lines = [
        f"# Codeforces 20-problem training set for {args.handle}",
        "",
        f"Source: {result['source']}. Generated: {result['generated_at_utc']}.",
        f"Filtered against {len(submissions)} real submissions / {len(attempted)} distinct attempted problems.",
        "No previously submitted problems are included. Each problem has a distinct contest ID.",
        "Every primary focus appears once except DP (twice). Original Codeforces tags may overlap.",
        "",
        "| # | Rating | Primary topic | Problem | Other official tags |",
        "|---:|---:|---|---|---|",
    ]
    for p in selected:
        extra = ", ".join(t for t in p["tags"] if t != p["focus"]) or "—"
        lines.append(
            f"| {p['number']} | {p['rating']} | {p['focus']} | "
            f"[{p['name']}]({p['url']}) | {extra} |"
        )
    lines += [
        "",
        "## Training protocol",
        "",
        "- Work in displayed order for a progressive difficulty ladder.",
        "- Each problem: independent first attempt, then optional hint, then editorial after the cap.",
        "- Suggested caps: 1100=30 min, 1200=40 min, 1300=50 min, 1400=65 min, 1500=75 min.",
        "- Track outcome, minutes, whether hints/editorial were used, and first-submit verdict.",
        "- Only mark a problem as independently solved if no hints/editorial were used.",
        "",
    ]
    (args.out / "training_20.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"SELECTED {len(selected)} NEW problems => {args.out}", flush=True)
    for p in selected:
        print(f"{p['number']:2d}. {p['rating']} {p['focus']:<24} {p['name']} {p['url']}", flush=True)


if __name__ == "__main__":
    main()
